#!/usr/bin/env bun
/**
 * Rebuild `src/data/sports-catalogue.json` from the odds provider's own list of
 * competitions.
 *
 * Why this exists: the Lay Bet Finder used to ask the provider for its generic
 * `upcoming` endpoint, which returns 8–14 events across ALL sports (a real check
 * returned 8 events, all ATP tennis, zero football). Asking per competition is
 * how you get EPL 21 / Championship 12 / Champions League 18. The list of
 * competitions therefore has to come from the provider, not from a hardcoded
 * array in a page — this script is the one place it is written down.
 *
 * COST: `GET /v4/sports/` costs **0 credits** (`x-requests-last: 0`, verified
 * 2026-10-28). Re-run it whenever the provider adds or drops a competition:
 *
 *     bun scripts/build-sports-catalogue.ts
 *
 * The endpoint validates every requested key against this file, so a competition
 * that disappears from the provider cannot silently burn a credit.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(import.meta.dir, "..", "src", "data", "sports-catalogue.json");

/** Competitions a new visitor starts with — the ones the owner asked for. */
const DEFAULT_KEYS = ["soccer_epl", "soccer_efl_champ", "soccer_uefa_champs_league"];

/**
 * Readable names where the provider's title is an abbreviation or ambiguous.
 * Presentation only — never used for validation or routing.
 */
const LABELS: Record<string, string> = {
  soccer_epl: "Premier League (EPL)",
  soccer_efl_champ: "Championship (England)",
  soccer_uefa_champs_league: "Champions League (UEFA)",
  soccer_uefa_europa_league: "Europa League (UEFA)",
  soccer_uefa_europa_conference_league: "Conference League (UEFA)",
  soccer_spain_la_liga: "La Liga (Spain)",
  soccer_italy_serie_a: "Serie A (Italy)",
  soccer_germany_bundesliga: "Bundesliga (Germany)",
  soccer_france_ligue_one: "Ligue 1 (France)",
  soccer_spl: "Scottish Premiership",
  soccer_england_league1: "League One (England)",
  soccer_england_league2: "League Two (England)",
  soccer_england_efl_cup: "EFL Cup (England)",
};

interface ProviderSport {
  key: string;
  group: string;
  title: string;
  active: boolean;
  has_outrights?: boolean;
}

/** "Bundesliga - Germany" → "Bundesliga (Germany)". Unchanged when no suffix. */
function tidyLabel(sport: ProviderSport): string {
  if (LABELS[sport.key]) return LABELS[sport.key];
  const dash = sport.title.lastIndexOf(" - ");
  if (dash > 0) return `${sport.title.slice(0, dash)} (${sport.title.slice(dash + 3)})`;
  return sport.title;
}

function apiKey(): string {
  const key = (process.env.ODDS_API_KEY || process.env.Oddsapi || "").trim();
  if (!key) {
    console.error(
      "[catalogue] No odds API key in this environment (ODDS_API_KEY / Oddsapi).\n" +
        "The catalogue is unchanged — this script needs the key only to read the provider's list.",
    );
    process.exit(1);
  }
  return key;
}

const res = await fetch(`https://api.the-odds-api.com/v4/sports/?apiKey=${apiKey()}`);
const cost = res.headers.get("x-requests-last");
if (!res.ok) {
  console.error(`[catalogue] provider returned ${res.status} — nothing written`);
  process.exit(1);
}
const raw = (await res.json()) as ProviderSport[];

// Ice hockey is excluded at the data layer (regulation-time back odds vs
// overtime-inclusive lays never line up), so it must never appear as a
// selectable competition here either — a search over it could only ever
// return zero rows and would still cost a credit.
// Outright ("… Winner") keys are excluded too: they are futures markets, not
// fixtures, and the finder's back/lay pairs only make sense on a fixture.
const sports = raw
  .filter((s) => s.active && !s.has_outrights && !s.key.startsWith("icehockey_"))
  .map((s) => ({ key: s.key, title: s.title, label: tidyLabel(s), group: s.group, outrights: Boolean(s.has_outrights) }))
  .sort((a, b) => a.group.localeCompare(b.group) || a.label.localeCompare(b.label));

const missingDefaults = DEFAULT_KEYS.filter((k) => !sports.some((s) => s.key === k));
if (missingDefaults.length) {
  console.warn(`[catalogue] ⚠️ default competitions missing from the feed: ${missingDefaults.join(", ")}`);
}

const payload = {
  generatedAt: new Date().toISOString(),
  source: "https://api.the-odds-api.com/v4/sports/?all=false",
  creditCostOfThisFile: Number(cost ?? 0),
  note:
    "Generated by scripts/build-sports-catalogue.ts from the odds provider's own competition list. " +
    "Do not hand-edit: re-run the script. Ice hockey is excluded on purpose (its back and lay prices describe different markets).",
  defaultKeys: DEFAULT_KEYS.filter((k) => sports.some((s) => s.key === k)),
  sports,
};

writeFileSync(OUT, JSON.stringify(payload, null, 2) + "\n");
console.log(
  `[catalogue] wrote ${sports.length} active competitions to ${OUT} (cost: ${cost ?? "?"} credits)\n` +
    `[catalogue] defaults: ${payload.defaultKeys.join(", ")}`,
);
